import Foundation

/// What the overlay shows. Scratch is the heads-up pad, Clipboard is
/// editable clipboard history, and each project has a Context pad
/// holding its live context.
public enum Pad: Hashable, Codable, Sendable {
    case scratch
    case clipboard
    case project(String)

    public var title: String {
        switch self {
        case .scratch: "Scratch"
        case .clipboard: "Clipboard"
        case .project(let name): name
        }
    }

    public var isProject: Bool {
        if case .project = self { return true }
        return false
    }
}

/// What the clipboard watcher keeps. Password managers mark secrets with
/// the nspasteboard.org concealed/transient types; those are never kept.
public enum ClipboardPolicy {
    public static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]
    public static let maxCharacters = 200_000
    /// Untouched entries leave after this long; editing one keeps it.
    public static let lifetime: TimeInterval = 30 * 24 * 3600

    public static func shouldCapture(text: String?, types: [String], previous: String?) -> Bool {
        guard let text, !types.contains(where: skippedTypes.contains) else { return false }
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty, text.count <= maxCharacters else { return false }
        return text != previous
    }
}

extension PlainText {
    /// Paste that keeps Markdown: lists, quotes, tables, and code survive.
    /// Only invisible junk is normalized — line endings, non-breaking and
    /// zero-width spaces — so pasted text reads the same in any editor.
    public static func normalizePaste(_ input: String) -> String {
        var text = input.replacingOccurrences(of: "\r\n", with: "\n").replacingOccurrences(of: "\r", with: "\n")
        text = text.replacingOccurrences(of: "\u{00A0}", with: " ")
        for invisible in ["\u{200B}", "\u{200C}", "\u{200D}", "\u{FEFF}"] {
            text = text.replacingOccurrences(of: invisible, with: "")
        }
        return text
    }
}
